#!/usr/bin/env node
/**
 * P024 FIX T013 (P2-11) -- release build.
 *
 *   npm run release:build
 *
 * The frozen package.json script `release:build` had no file behind it.
 * This script is the packaging half of T012's release rehearsal
 * (scripts/release-rehearsal.mjs), split out so the frozen script
 * exists and runs on its own:
 *
 *   1. `npm run build`
 *   2. Stage the source tree and the dist tree (same file lists as
 *      the rehearsal: source gets package.json, package-lock.json,
 *      tsconfigs, src/, oracle/, tests/, demo/, docs/, scripts/,
 *      README, LICENSE and .github; dist gets dist/ plus
 *      package.json, package-lock.json, README, LICENSE).
 *   3. Zip both trees and write SHA256SUMS.txt.
 *
 * Output goes to a scratch directory under TMPDIR (default
 * <repo>/.tmp/release-build) -- NOT 05_release/, which is T014's.
 * The packages are verified by `npm run release:verify`.
 * Exits 0 only when the build and both packages succeed.
 *
 * Reproducibility (FIX T013 R2, R2-P2-01): plain `zip -qr -X` embeds
 * each entry's mtime, so two runs staged at different times produced
 * different zip SHAs. Before zipping, every staged entry (files, dirs,
 * symlinks) is pinned to one fixed timestamp -- SOURCE_DATE_EPOCH when
 * set, else the HEAD commit time, else a fixed fallback -- so the same
 * commit always produces byte-identical zips. Node's `cpSync` also
 * rewrites relative symlinks to ABSOLUTE targets in the copy, which
 * makes `zip` timestamp the link from its (out-of-stage, worktree)
 * target file; staged symlinks are therefore re-relativized first, so
 * the package carries the same relative link as the repo.
 *
 * FIX T014 (packaging defects, T014 NO-GO): the staged tree already
 * carried symlinks correctly -- `cpSync` preserves them -- but plain
 * `zip` FOLLOWS symlinks by default and stores the target's content
 * as a regular file, so the shipped source.zip failed its own test
 * suite (py-symlink-snapshot 276/277). The zip step therefore uses
 * `-y` (--symlinks) to store links as links. The same round also
 * prunes generated bytecode (`*.pyc`, and any `__pycache__/` dir left
 * empty by that prune) from the stage -- the wholesale directory
 * copies previously swept in the Oracle `.pyc` -- while KEEPING
 * deliberate `__pycache__/` fixture files (e.g. the go/ts-pycache
 * regression inputs, now tracked), which are non-empty after the
 * prune. `.npmignore` is staged, and LICENSE is read from the source
 * dir first (repo-root fallback) so the script is self-hosting from
 * an extracted source.zip.
 */
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  cpSync,
  existsSync,
  lstatSync,
  lutimesSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  readlinkSync,
  rmSync,
  symlinkSync,
  unlinkSync,
  utimesSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const SRC_DIR = join(SCRIPT_DIR, "..");
const REPO_ROOT = join(SRC_DIR, "..");
const TMPDIR = process.env.TMPDIR || join(REPO_ROOT, ".tmp");
const OUT = join(TMPDIR, "release-build");

const failures = [];
function log(msg) {
  console.log(msg);
}
function fail(msg) {
  failures.push(msg);
  log(`FAIL: ${msg}`);
}
function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, {
    cwd: opts.cwd ?? SRC_DIR,
    encoding: "utf8",
    env: { ...process.env, TMPDIR },
  });
  log(`$ ${cmd} ${args.join(" ")}  (cwd: ${opts.cwd ?? SRC_DIR})`);
  if (r.stdout?.trim()) log(r.stdout.trimEnd());
  if (r.stderr?.trim()) log(`stderr: ${r.stderr.trimEnd()}`);
  log(`exit code: ${r.status}`);
  return r;
}
function sha256File(path) {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

/**
 * Fixed timestamp (epoch seconds) for reproducible zips (R2-P2-01).
 * Precedence: $SOURCE_DATE_EPOCH, else the HEAD commit time (same
 * commit => same timestamp), else a fixed fallback for trees without
 * git history (e.g. a source.zip extraction re-running the build).
 */
function releaseEpochSeconds() {
  const fromEnv = Number(process.env.SOURCE_DATE_EPOCH);
  if (Number.isInteger(fromEnv) && fromEnv > 0) return fromEnv;
  const git = spawnSync("git", ["-C", REPO_ROOT, "log", "-1", "--format=%ct"], {
    encoding: "utf8",
  });
  const fromGit = Number((git.stdout ?? "").trim());
  if (git.status === 0 && Number.isInteger(fromGit) && fromGit > 0) return fromGit;
  return 1735689600; // 2025-01-01T00:00:00Z
}

/**
 * LICENSE source (FIX T014). Prefer the LICENSE inside the source dir
 * (shipped in source.zip); fall back to the repo-root LICENSE. The old
 * code read only the repo-root path, so `npm run release:build` crashed
 * with ENOENT in an extracted source.zip, where no parent LICENSE exists.
 */
function licenseSource() {
  if (existsSync(join(SRC_DIR, "LICENSE"))) return join(SRC_DIR, "LICENSE");
  return join(REPO_ROOT, "LICENSE");
}

/**
 * Prune generated bytecode from a staged tree (FIX T014). Deletes every
 * `*.pyc` file, then removes any `__pycache__/` directory left empty by
 * that prune (e.g. oracle/python/__pycache__/ holding only the compiled
 * oracle). Deliberate `__pycache__/` fixture dirs are NOT removed: they
 * hold non-bytecode test inputs (go/ts-pycache x.go / stray.ts) and stay
 * non-empty after the prune, so they survive.
 */
function pruneGeneratedCaches(dir) {
  const walk = (d) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name);
      const st = lstatSync(p);
      if (st.isSymbolicLink()) continue;
      if (st.isDirectory()) {
        walk(p);
        if (
          name === "__pycache__" &&
          readdirSync(p).length === 0
        ) {
          rmSync(p, { recursive: true, force: true });
          log(`pruned empty generated cache dir: ${relative(dir, p)}`);
        }
        continue;
      }
      if (name.endsWith(".pyc")) {
        rmSync(p, { force: true });
        log(`pruned generated bytecode: ${relative(dir, p)}`);
      }
    }
  };
  walk(dir);
}

/** Pin atime/mtime of every entry under `dir` (incl. the dir itself) to the fixed timestamp. */
function pinMtimes(dir, epochSeconds) {
  const date = new Date(epochSeconds * 1000);
  const walk = (d) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name);
      const st = lstatSync(p);
      if (st.isDirectory() && !st.isSymbolicLink()) walk(p);
      try {
        if (st.isSymbolicLink()) lutimesSync(p, date, date);
        else utimesSync(p, date, date);
      } catch {
        // Symlink times are best-effort on some platforms; the link
        // target bytes (what the zip hashes for content) are unaffected.
      }
    }
  };
  walk(dir);
  utimesSync(dir, date, date);
}

/**
 * Re-relativize staged symlinks. Node's cpSync rewrites a relative
 * symlink target to an ABSOLUTE path in the copy (verified on Node
 * 24.22.1), so a staged link escapes the stage tree and `zip` timestamps
 * (and, on extraction, resolves) it against the builder's worktree
 * file -- a different mtime on every checkout, and a dangling link in
 * the package. Rewrite each absolute in-tree target back to the
 * relative spelling it has in the repo; links pointing outside the
 * mirrored tree are left alone and logged. `srcRoot` is the tree the
 * stage dir mirrors (SRC_DIR for the source stage, SRC_DIR/dist for
 * the dist stage).
 */
function rewriteStagedSymlinks(dir, srcRoot) {
  const walk = (d) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name);
      const st = lstatSync(p);
      if (st.isDirectory() && !st.isSymbolicLink()) {
        walk(p);
        continue;
      }
      if (!st.isSymbolicLink()) continue;
      const target = readlinkSync(p);
      if (!target.startsWith(sep)) continue; // already relative
      const resolved = resolve(target);
      if (resolved !== srcRoot && !resolved.startsWith(srcRoot + sep)) {
        log(`WARN: staged symlink left absolute (target outside mirrored tree): ${relative(dir, p)} -> ${target}`);
        continue;
      }
      const relTarget = relative(dirname(p), resolve(dir, relative(srcRoot, resolved)));
      unlinkSync(p);
      symlinkSync(relTarget, p);
      log(`re-relativized staged symlink: ${relative(dir, p)} -> ${relTarget}`);
    }
  };
  walk(dir);
}

log("== release:build ==");
log(`output dir: ${OUT}`);
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const build = run("npm", ["run", "build"]);
if (build.status !== 0) fail("npm run build failed");

const stageSrc = join(OUT, "stage-src");
mkdirSync(stageSrc, { recursive: true });
for (const f of ["package.json", "package-lock.json", "tsconfig.json", "tsconfig.build.json", "README.md", ".npmignore"]) {
  cpSync(join(SRC_DIR, f), join(stageSrc, f));
}
cpSync(licenseSource(), join(stageSrc, "LICENSE"));
for (const d of ["src", "oracle", "tests", "demo", "docs", "scripts"]) {
  cpSync(join(SRC_DIR, d), join(stageSrc, d), { recursive: true, dereference: false });
}
if (existsSync(join(SRC_DIR, ".github"))) {
  cpSync(join(SRC_DIR, ".github"), join(stageSrc, ".github"), { recursive: true, dereference: false });
}
rmSync(join(stageSrc, "demo", "out"), { recursive: true, force: true });
pruneGeneratedCaches(stageSrc);
log(`staged source tree: ${readdirSync(stageSrc).join(", ")}`);

const stageDist = join(OUT, "stage-dist");
mkdirSync(stageDist, { recursive: true });
cpSync(join(SRC_DIR, "dist"), join(stageDist, "dist"), { recursive: true, dereference: false });
for (const f of ["package.json", "package-lock.json", "README.md"]) {
  cpSync(join(SRC_DIR, f), join(stageDist, f));
}
cpSync(licenseSource(), join(stageDist, "LICENSE"));
pruneGeneratedCaches(stageDist);
log(`staged dist tree: ${readdirSync(stageDist).join(", ")}`);

// R2-P2-01: pin every staged entry's mtime so the zips are
// reproducible (same commit => byte-identical zips). Re-relativize
// staged symlinks first (cpSync absolutizes them; see above), so `zip`
// timestamps each link from its in-stage target, not the worktree.
rewriteStagedSymlinks(stageSrc, SRC_DIR);
rewriteStagedSymlinks(stageDist, join(SRC_DIR, "dist"));
const epoch = releaseEpochSeconds();
log(
  `reproducible-build timestamp: ${epoch} (${new Date(epoch * 1000).toISOString()})`,
);
pinMtimes(stageSrc, epoch);
pinMtimes(stageDist, epoch);

const zipSrc = run("zip", ["-qr", "-X", "-y", join(OUT, "source.zip"), "."], { cwd: stageSrc });
if (zipSrc.status !== 0) fail("zip source.zip failed");
const zipDist = run("zip", ["-qr", "-X", "-y", join(OUT, "dist.zip"), "."], { cwd: stageDist });
if (zipDist.status !== 0) fail("zip dist.zip failed");
const sums = run("sha256sum", ["source.zip", "dist.zip"], { cwd: OUT });
if (sums.status !== 0) fail("sha256sum failed");
writeFileSync(join(OUT, "SHA256SUMS.txt"), sums.stdout);
log(`source.zip sha256: ${sha256File(join(OUT, "source.zip"))}`);
log(`dist.zip sha256:   ${sha256File(join(OUT, "dist.zip"))}`);
log("SHA256SUMS.txt:");
log(readFileSync(join(OUT, "SHA256SUMS.txt"), "utf8").trimEnd());

if (failures.length > 0) {
  log(`RELEASE:BUILD FAILED (${failures.length} failure(s))`);
  process.exit(1);
}
log("RELEASE:BUILD PASS: source.zip + dist.zip + SHA256SUMS.txt written.");
