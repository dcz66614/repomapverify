# FIX P024 R2 P1-01: TS parse-config states. A config file
# (tsconfig.json / package.json) is ABSENT (no file), OK (read and
# parsed), UNREADABLE (exists but cannot be read), or MALFORMED
# (exists but cannot be parsed). UNREADABLE / MALFORMED is UNKNOWN,
# never a default configuration: the R1 P1-01 fallback ("an
# unreadable config reads as absent", production loadTsConfig /
# loadPackageJson returning undefined on any read failure) silently
# turned real local imports into external ones, and the Oracle
# mirrored the same default, so parity could not catch it.
# The unknown-import reason is a single value, exactly like
# production (resolve.ts "CONFIG_UNREADABLE", emitted both for a
# bad config's own entry and for imports that may depend on it):
# which config failed, and whether it failed to read or to parse,
# is recorded in the ground truth (gt tsconfigStatus /
# packageJsonStatus: "UNREADABLE" / "MALFORMED", the BuiltGraph
# typescriptConfigProblems vocabulary) and in the finding's `from`,
# not in the reason string -- so Oracle-vs-production comparison
# of unknownImports agrees field for field.
CONFIG_UNREADABLE_REASON = "CONFIG_UNREADABLE"


