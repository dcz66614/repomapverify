    # -- resolution ------------------------------------------------------
    def _dir_has_package(self, dir_rel):
        return dir_rel in self._packages

    def _resolve_import(self, import_path):
        """Returns ("edge", package dir rel) | ("external", None) |
        ("unknown", reason)."""
        if import_path == "C":
            return ("cgo", None)
        # replace directives (longest matching old prefix wins)
        path = import_path
        for old in sorted(self.gomod["replace"], key=len, reverse=True):
            if path == old or path.startswith(old + "/"):
                new = self.gomod["replace"][old]
                rest = path[len(old):]
                if new.startswith("./") or new.startswith("../"):
                    # local directory replace, relative to repo root
                    base = normalize_rel(new)
                    cand = normalize_rel(base + rest) if rest else base
                    if self._dir_has_package(cand):
                        return ("edge", cand)
                    return ("unknown", "TARGET_PACKAGE_NOT_FOUND")
                path = new + rest
                break
        module = self.gomod["module"]
        if module and (path == module or path.startswith(module + "/")):
            rest = path[len(module):].lstrip("/")
            cand = rest if rest else "."
            if self._dir_has_package(cand):
                return ("edge", cand)
            if self._dir_exists(cand):
                return ("unknown", "TARGET_PACKAGE_EMPTY")
            return ("unknown", "TARGET_PACKAGE_NOT_FOUND")
        if "/" not in path.split("/")[0] and "." not in path.split("/")[0]:
            # first segment has no dot: standard library (fmt, os, ...)
            return ("external", None)
        # external module path: vendor/ wins, otherwise external
        vendored = f"vendor/{path}"
        if self._dir_has_package(vendored):
            return ("edge", vendored)
        if "." in path.split("/")[0]:
            return ("external", None)
        return ("external", None)

    def _dir_exists(self, dir_rel):
        return os.path.isdir(os.path.join(self.repo_root, dir_rel))

    # -- extraction ------------------------------------------------------
    def extract(self):
        # Pass 1: classify files, group into packages.
        self._packages = {}   # dir -> {"files": [...], "packageName": str,
                              #         "hasCgo": bool, "parseError": bool}
        excluded = []
        unknowns = []
        imports_by_file = {}  # rel -> [(import_path, line)]
        # FIX P024 R1 P1-01: package directories holding at least one
        # unreadable constituent file (their package node survives from
        # readable files, but its composition is incomplete).
        unreadable_file_dirs = set()
        # FIX P024 R1 P1-01: directories that could not be listed hold
        # UNKNOWN content. Each becomes an UNREADABLE unknown with the
        # identical shape production emits, so the two verdicts agree.
        for d in self.unreadable_dirs:
            unknowns.append({"from": d, "specifier": "",
                             "reason": "UNREADABLE", "line": 1})
        for rel in self.files:
            full = os.path.join(self.repo_root, rel)
            dir_rel = "/".join(rel.split("/")[:-1]) or "."
            # FIX P024 R1 P1-01: the _test.go exclusion is decided by
            # NAME, before any read -- an unreadable test file is still
            # a test file (never part of the build graph), so it is
            # excluded without a finding. Production mirrors this order.
            if rel.endswith("_test.go"):
                excluded.append({"relativePath": rel, "reason": "TEST_FILE"})
                continue
            try:
                data = open(full, "rb").read()
            except PermissionError:
                # FIX P024 R1 P1-01: a listed-but-unreadable file is
                # UNKNOWN content, not a missing file. It contributes
                # no content hash and no imports (never guessed), but
                # its package is marked UNREADABLE below and the file
                # itself is recorded here so the comparator can name
                # it -- mirroring production
                # (src/extractors/go/index.ts). When it is the
                # package's ONLY file, this entry is the only trace
                # of it at all.
                unreadable_file_dirs.add(dir_rel)
                unknowns.append({"from": rel, "specifier": "",
                                 "reason": "UNREADABLE", "line": 1})
                continue
            content_sha = sha256_hex(data)
            try:
                text = data.decode("utf-8")
            except UnicodeDecodeError:
                text = ""
            in_build, undecidable = file_in_build(text)
            if undecidable is not None:
                excluded.append({"relativePath": rel,
                                 "reason": "UNDECIDABLE_BUILD_CONSTRAINT"})
                unknowns.append({"from": dir_rel, "specifier": "",
                                 "reason": "UNDECIDABLE_BUILD_CONSTRAINT",
                                 "line": 1})
                continue
            if not in_build:
                excluded.append({"relativePath": rel,
                                 "reason": "BUILD_EXCLUDED"})
                continue
            generated = rel.endswith(".pb.go") or rel.endswith(".mock.go") \
                or is_generated_content(text)
            pkg_name, raw_imports, parse_error = self._parse_go_file(text)
            if parse_error:
                unknowns.append({"from": dir_rel, "specifier": "",
                                 "reason": "PARSE_ERROR", "line": 1})
            is_cgo = any(p == "C" for p, _ in raw_imports)
            rec = {"relativePath": rel, "contentSha256": content_sha,
                   "isGenerated": generated, "isCgo": is_cgo}
            pkg = self._packages.setdefault(
                dir_rel, {"files": [], "packageName": pkg_name,
                          "hasCgo": False, "parseError": False})
            pkg["files"].append(rec)
            if pkg_name:
                if not pkg["packageName"]:
                    pkg["packageName"] = pkg_name
                elif pkg["packageName"] != pkg_name:
                    unknowns.append({"from": dir_rel, "specifier": "",
                                     "reason": "PARSE_ERROR", "line": 1})
                    pkg["parseError"] = True
            pkg["hasCgo"] = pkg["hasCgo"] or is_cgo
            pkg["parseError"] = pkg["parseError"] or parse_error
            imports_by_file[rel] = raw_imports
        # Pass 2: package nodes.
        modules = []
        for dir_rel in sorted(self._packages):
            pkg = self._packages[dir_rel]
            files = sorted(pkg["files"], key=lambda f: f["relativePath"])
            content_sha = go_package_hash(files)
            module_id_input = "" if dir_rel == "." else dir_rel
            modules.append({
                "relativePath": dir_rel,
                "moduleId": module_id("go", module_id_input),
                "contentSha256": content_sha,
                "language": "go",
                "nodeKind": "package",
                "isGenerated": bool(files) and all(f["isGenerated"] for f in files),
                "isEntrypoint": dir_rel in self.entrypoints,
                # FIX P024 R1 P1-01: worst-status rule, mirroring
                # production (src/extractors/go/index.ts): PARSE_ERROR
                # > UNREADABLE > OK. A package with an unreadable
                # constituent file is incompletely enumerated.
                "parseStatus": ("PARSE_ERROR" if pkg["parseError"]
                                else "UNREADABLE"
                                if dir_rel in unreadable_file_dirs
                                else "OK"),
                "packageName": pkg["packageName"],
                "hasCgo": pkg["hasCgo"],
                "files": files,
            })
        # Pass 3: edges (per source file, so generated files split out).
        edges = {}
        gen_edges = {}
        external_count = 0
        for rel in sorted(imports_by_file):
            dir_rel = "/".join(rel.split("/")[:-1]) or "."
            generated = self._file_generated(rel)
            for import_path, line in imports_by_file[rel]:
                status, value = self._resolve_import(import_path)
                if status == "edge":
                    if value == dir_rel:
                        continue  # intra-package: no edge
                    rec = {"from": dir_rel, "to": value, "conditional": False,
                           "typeOnly": False,
                           "evidence": {"line": line, "statement": None,
                                        "specifier": import_path,
                                        "file": rel},
                           "kind": None}
                    bucket = gen_edges if generated else edges
                    key = (dir_rel, value)
                    if key not in bucket:
                        bucket[key] = rec
                elif status == "external":
                    external_count += 1
                elif status == "cgo":
                    pass
                else:
                    unknowns.append({"from": dir_rel,
                                     "specifier": import_path,
                                     "reason": value, "line": line})
        # FIX T013 R4 (R4-P1-01): resolve declared entrypoints against
        # the extracted packages, mirroring production (see
        # PythonOracle.extract). A literal such as
        # "cmd/server/main.go" resolves to its package dir "cmd/server";
        # a literal whose package does not exist (e.g.
        # "cmd/ghost/main.go") drops out of the GT `entrypoints` list
        # and is recorded in self.unresolved_entrypoints. A literal
        # naming a package directory directly ("cmd/server") does NOT
        # resolve, exactly like production.
        resolved, unresolved = _resolve_declared_entrypoints(
            self.entrypoint_literal_paths, modules)
        self.entrypoints = resolved
        self.unresolved_entrypoints = unresolved
        resolved_set = set(resolved)
        for m in modules:
            m["isEntrypoint"] = m["relativePath"] in resolved_set
        gt = {
            "modules": modules,
            "edges": sorted(edges.values(),
                            key=lambda e: (e["from"], e["to"], e["evidence"]["line"])),
            "generatedEdges": sorted(gen_edges.values(),
                                     key=lambda e: (e["from"], e["to"], e["evidence"]["line"])),
            "entrypoints": sorted(self.entrypoints),
            "externalImportCount": external_count,
            "externalImports": [],
            "unknownImports": sorted(
                unknowns, key=lambda x: (x["from"], x["specifier"], x["line"])),
            "dynamicUnknown": [],
            "excludedFiles": sorted(excluded, key=lambda x: x["relativePath"]),
        }
        gt["reachableFromEntrypoints"], gt["isolatedModules"] = \
            _reachability_bfs(gt["modules"], gt["edges"], self.entrypoints)
        gt["repoSnapshotSha256"] = snapshot_sha256(self.repo_root)
        # FIX P024 R1 P1-01 follow-up: see PythonOracle.extract.
        if self.entrypoints_declaration_unreadable:
            gt["entrypointsDeclarationUnreadable"] = True
        return gt

    def _file_generated(self, rel):
        for pkg in self._packages.values():
            for f in pkg["files"]:
                if f["relativePath"] == rel:
                    return f["isGenerated"]
        return False

    @staticmethod
    def _parse_go_file(text):
        """Returns (package_name, [(import_path, line)], parse_error).
        Line-anchored import parsing: only lines starting with `import`
        are considered, so string literals elsewhere can never be mistaken
        for imports. An unbalanced file is PARSE_ERROR (imports dropped)."""
        clean = strip_comments(text)
        lines = clean.split("\n")
        pkg_name = ""
        for line in lines:
            m = re.match(r"^\s*package\s+([A-Za-z_][A-Za-z0-9_]*)\s*$", line)
            if m:
                pkg_name = m.group(1)
                break
        parse_error = not balanced(text) or not pkg_name
        imports = []
        i = 0
        while i < len(lines):
            s = lines[i].strip()
            if not s.startswith("import"):
                i += 1
                continue
            m = re.match(r"^import\s+(?:[A-Za-z_.]+\s+)?\"([^\"]+)\"\s*;?\s*$", s)
            if m:
                imports.append((m.group(1), i + 1))
                i += 1
                continue
            if re.match(r"^import\s*\(\s*$", s):
                i += 1
                while i < len(lines):
                    entry = lines[i].strip()
                    if entry.startswith(")"):
                        break
                    m2 = re.match(
                        r"^(?:[A-Za-z_.]+\s+)?\"([^\"]+)\"", entry)
                    if m2:
                        imports.append((m2.group(1), i + 1))
                    i += 1
                i += 1
                continue
            # import line no pattern matched: the file is not in the frozen
            # scope -- mark it PARSE_ERROR rather than silently dropping
            # the import (UNKNOWN, never a silent pass).
            return pkg_name, imports, True
        imports = [(p, ln) for (p, ln) in imports
                   if not p.startswith("__UNPARSED__")]
        return pkg_name, imports, parse_error


