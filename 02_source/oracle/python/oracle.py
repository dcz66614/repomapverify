    def _load_tsconfig(self):
        """Returns (config, status): status is ABSENT / OK /
        UNREADABLE / MALFORMED.

        FIX P024 R2 P1-01: supersedes the R1 P1-01 fallback, which
        returned the default config {"baseUrl": ".", "paths": {}} for
        an unreadable or unparseable tsconfig -- exactly the blind
        spot R2-P1-01 reports (production loadTsConfig did the same
        by returning undefined). A config that exists but cannot be
        read or parsed is UNKNOWN: the default is returned only as a
        placeholder value (resolve() consults it only when the
        status is OK or ABSENT), never as a reading of the file.
        Malformed-but-parseable fields are STRICT (FIX P024 R3
        P1-02, shared with production resolve.ts loadTsConfig):
        a non-string baseUrl is ignored ("."), but a paths value
        that is not an array, or an array containing a non-string
        target, is MALFORMED -- the R2 tolerance (drop non-array
        values, filter non-string targets) silently discarded real
        configuration and is abolished. A non-dict top level, a
        non-dict compilerOptions, or a non-dict paths is MALFORMED:
        the shape itself is not a tsconfig.
        FIX P024 R3 P1-01: the returned config records `hasExtends`
        (the top-level `extends` field is present, whatever its
        value -- production `raw.extends !== undefined`). An
        inherited alias is outside the frozen resolution scope, so
        resolve() must never guess `external` for a bare specifier
        while hasExtends is true (see resolve()).
        """
        path = os.path.join(self.repo_root, "tsconfig.json")
        default = {"baseUrl": ".", "paths": {}, "hasExtends": False}
        if not os.path.exists(path):
            return dict(default), "ABSENT"
        try:
            with open(path, "r", encoding="utf-8") as fh:
                raw = _strip_json_comments(fh.read())
        except PermissionError:
            return dict(default), "UNREADABLE"
        except UnicodeDecodeError:
            return dict(default), "MALFORMED"
        except OSError:
            return dict(default), "UNREADABLE"
        try:
            data = json.loads(raw)
        except json.JSONDecodeError:
            return dict(default), "MALFORMED"
        if not isinstance(data, dict):
            return dict(default), "MALFORMED"
        opts = data.get("compilerOptions", {})
        if not isinstance(opts, dict):
            return dict(default), "MALFORMED"
        paths = opts.get("paths", {})
        if not isinstance(paths, dict):
            return dict(default), "MALFORMED"
        clean_paths = {}
        for pattern, targets in paths.items():
            # FIX P024 R3 P1-02: strict paths validation (shared
            # with production). A non-array value or a non-string
            # element is MALFORMED, not silently dropped/filtered.
            if not isinstance(targets, list):
                return dict(default), "MALFORMED"
            if not all(isinstance(t, str) for t in targets):
                return dict(default), "MALFORMED"
            clean_paths[pattern] = list(targets)
        base_url = opts.get("baseUrl", ".")
        if not isinstance(base_url, str):
            base_url = "."
        return {"baseUrl": base_url, "paths": clean_paths,
                "hasExtends": "extends" in data}, "OK"

    def _load_package_json(self):
        """Returns (data, status): status is ABSENT / OK /
        UNREADABLE / MALFORMED.

        FIX P024 R2 P1-01: supersedes the R1 P1-01 fallback, which
        returned {} for an unreadable or unparseable package.json.
        A package.json that exists but cannot be read or parsed is
        UNKNOWN: the empty object is only a placeholder (resolve()
        consults it only when the status is OK or ABSENT).
        FIX P024 R3 P1-02: a `name` field that is present but is not
        a non-empty string is MALFORMED (shared with production
        resolve.ts loadPackageJson): an explicitly supplied name
        must not be silently dropped into "no name", or a
        self-reference the config claims to define is quietly
        treated as an external package. Absent `name` is normal.
        """
        path = os.path.join(self.repo_root, "package.json")
        if not os.path.exists(path):
            return {}, "ABSENT"
        try:
            with open(path, "r", encoding="utf-8") as fh:
                data = json.load(fh)
        except PermissionError:
            return {}, "UNREADABLE"
        except UnicodeDecodeError:
            return {}, "MALFORMED"
        except json.JSONDecodeError:
            return {}, "MALFORMED"
        except OSError:
            return {}, "UNREADABLE"
        if not isinstance(data, dict):
            return {}, "MALFORMED"
        if "name" in data and (not isinstance(data["name"], str)
                               or data["name"] == ""):
            return {}, "MALFORMED"
        return data, "OK"

    # -- resolution ------------------------------------------------------
    def _try_file(self, candidate_rel):
        """candidate_rel: repo-relative POSIX path (no leading ./).
        Returns the existing file path, or None."""
        cand = normalize_rel(candidate_rel)
        if cand in self._file_set:
            return cand
        return None

    def _complete(self, base_rel):
        """Extension completion for a relative base (no extension, or a
        .js/.jsx that maps onto .ts/.tsx). Returns an existing file or
        None. Tries, in order: the base as written (with .js->.ts and
        .jsx->.tsx substitution), extension appends, index files."""
        bases = [base_rel]
        if base_rel.endswith(".js"):
            bases.append(base_rel[:-3] + ".ts")
        elif base_rel.endswith(".jsx"):
            bases.append(base_rel[:-4] + ".tsx")
        for base in bases:
            for ext in TS_EXT_COMPLETION:
                hit = self._try_file(base + ext)
                if hit:
                    return hit
            for idx in TS_INDEX_COMPLETION:
                hit = self._try_file(base + "/" + idx)
                if hit:
                    return hit
        return None

    def _resolve_relative(self, from_rel, spec):
        from_dir = "/".join(from_rel.split("/")[:-1])
        joined = normalize_rel(
            (from_dir + "/" + spec) if from_dir else spec)
        # collapse ".." segments lexically (spec is trusted fixture input)
        parts = []
        for seg in joined.split("/"):
            if seg == "..":
                if parts:
                    parts.pop()
                else:
                    return None  # escapes the repo root
            elif seg not in ("", "."):
                parts.append(seg)
        return self._complete("/".join(parts))

    def _resolve_paths_alias(self, spec):
        """tsconfig paths: pattern with a single * -> target list."""
        for pattern, targets in self.tsconfig["paths"].items():
            if "*" in pattern:
                prefix, suffix = pattern.split("*", 1)
                if spec.startswith(prefix) and spec.endswith(suffix) \
                        and len(spec) >= len(prefix) + len(suffix):
                    middle = spec[len(prefix):len(spec) - len(suffix)
                                   if suffix else len(spec)]
                    for target in targets:
                        subst = target.replace("*", middle)
                        base = normalize_rel(
                            (self.tsconfig["baseUrl"] + "/" + subst)
                            if self.tsconfig["baseUrl"] not in (".", "")
                            else subst)
                        hit = self._complete(base)
                        if hit:
                            return hit
                    return "TARGET_NOT_FOUND"
            else:
                if spec == pattern:
                    for target in targets:
                        base = normalize_rel(
                            (self.tsconfig["baseUrl"] + "/" + target)
                            if self.tsconfig["baseUrl"] not in (".", "")
                            else target)
                        hit = self._complete(base)
                        if hit:
                            return hit
                    return "TARGET_NOT_FOUND"
        return None

    def _resolve_exports(self, spec):
        """package.json exports (self-reference): exact "." key and
        "./prefix/*" patterns. A dict value resolves through its
        conditions, never through "types" alone (value imports)."""
        name = self.pkg.get("name")
        exports = self.pkg.get("exports")
        if not name or not isinstance(exports, dict):
            return None
        if spec != name and not spec.startswith(name + "/"):
            return None
        sub = "." if spec == name else "./" + spec[len(name) + 1:]
        target = None
        if sub in exports:
            target = exports[sub]
        else:
            for key, val in exports.items():
                if key.endswith("/*") and sub.startswith(key[:-1]):
                    target = val.replace("*", sub[len(key) - 1:]) \
                        if isinstance(val, str) else val
                    break
        if target is None:
            return None
        if isinstance(target, dict):
            for cond in ("import", "require", "node", "default"):
                if cond in target and isinstance(target[cond], str):
                    target = target[cond]
                    break
            else:
                return "TARGET_NOT_FOUND"
        if not isinstance(target, str):
            return "TARGET_NOT_FOUND"
        return self._complete(normalize_rel(target))

    def resolve(self, from_rel, spec):
        """Returns (kind, value): ("edge", repo-rel path),
        ("external", None), ("unknown", reason).

        FIX P024 R2 P1-01: resolution is per-config, not blanket.
        Each step runs only with the configs it depends on and that
        ARE known (OK or ABSENT -- ABSENT means "no such config",
        whose paths/exports/baseUrl are known to be empty). A step
        whose config is UNKNOWN (UNREADABLE / MALFORMED) is skipped,
        never run on a default: an unknown tsconfig's paths patterns
        and baseUrl are unknowable, an unknown package.json's name
        and exports are unknowable. A bare specifier that no known
        step resolves, while either config is UNKNOWN, is
        ("unknown", "CONFIG_UNREADABLE") -- never ("external",
        None) and never a silent drop -- because the skipped step
        may have resolved it. This mirrors production
        resolveSpecifier exactly (same frozen order: paths ->
        exports -> baseUrl -> bad-config fallthrough -> external),
        including the `node:` exemption: builtins do not depend on
        any config (production checks them before the config steps),
        so they stay external even while a config is unknown.
        FIX P024 R3 P1-01: the `node:` exemption is now explicit
        up front (same order as production: builtins are external
        regardless of config state, and regardless of hasExtends).
        A bare specifier that no known step resolves, while the
        tsconfig declares `extends`, is ("unknown",
        "ALIAS_NOT_RESOLVED") -- never ("external", None): the
        inherited config may define the alias, and the frozen scope
        does not resolve extends (boundary fixture
        ts-out-of-scope-extends README). The bad-config fallthrough
        above still wins over hasExtends: CONFIG_UNREADABLE has
        priority when a config is UNREADABLE / MALFORMED.
        """
        if spec.startswith("./") or spec.startswith("../"):
            hit = self._resolve_relative(from_rel, spec)
            if hit:
                return ("edge", hit)
            return ("unknown", "TARGET_NOT_FOUND")
        # FIX P024 R3 P1-01: node: builtins are external, before any
        # config step (production order). This subsumes the R2
        # bad-config exemption below, which is kept unchanged.
        if spec.startswith("node:"):
            return ("external", None)
        if self.tsconfig_status in ("OK", "ABSENT"):
            hit = self._resolve_paths_alias(spec)
            if isinstance(hit, str) and hit != "TARGET_NOT_FOUND":
                return ("edge", hit)
            if hit == "TARGET_NOT_FOUND":
                return ("unknown", "TARGET_NOT_FOUND")
        if self.pkg_status in ("OK", "ABSENT"):
            hit = self._resolve_exports(spec)
            if isinstance(hit, str) and hit != "TARGET_NOT_FOUND":
                return ("edge", hit)
            if hit == "TARGET_NOT_FOUND":
                return ("unknown", "TARGET_NOT_FOUND")
        # baseUrl fallback for bare specifiers (tsconfig-known only:
        # an unknown tsconfig's baseUrl is unknowable).
        if self.tsconfig_status in ("OK", "ABSENT"):
            base = self.tsconfig["baseUrl"]
            if base not in (".", "", None):
                hit = self._complete(normalize_rel(base + "/" + spec))
                if hit:
                    return ("edge", hit)
        # FIX P024 R2 P1-01: no known step resolved the specifier,
        # and at least one config it may have depended on is UNKNOWN.
        if self.tsconfig_status in ("UNREADABLE", "MALFORMED") \
                or self.pkg_status in ("UNREADABLE", "MALFORMED"):
            if spec.startswith("node:"):
                return ("external", None)
            return ("unknown", CONFIG_UNREADABLE_REASON)
        if spec.startswith("@/"):
            return ("unknown", "ALIAS_NOT_RESOLVED")
        if PACKAGE_NAME_RE.match(spec):
            # FIX P024 R3 P1-01: a bare specifier reaching the
            # external fallback while the tsconfig declares `extends`
            # may be an alias defined in the inherited config, which
            # is outside the frozen resolution scope: UNKNOWN with
            # reason ALIAS_NOT_RESOLVED, never external. `node:`
            # builtins never reach here (exempted up front).
            if self.tsconfig.get("hasExtends"):
                return ("unknown", "ALIAS_NOT_RESOLVED")
            return ("external", None)
        return ("unknown", "UNRESOLVABLE_SPECIFIER")

    # -- extraction ------------------------------------------------------
    def extract(self):
        self._file_set = set(self.files)
        modules = []
        edges = {}
        generated_edges = {}
        unknown = []
        external_count = 0
        # FIX P024 R1 P1-01: directories that could not be listed hold
        # UNKNOWN content. Each becomes an UNREADABLE unknown with the
        # identical shape production emits, so the two verdicts agree.
        for d in self.unreadable_dirs:
            unknown.append({"from": d, "specifier": "",
                            "reason": "UNREADABLE", "line": 1})
        # FIX P024 R2 P1-01: a TS parse config that exists but is
        # UNREADABLE or MALFORMED is UNKNOWN, not absent. Each becomes
        # an unknown entry naming the config file (same shape as the
        # unreadable-dir entries above, and exactly the shape
        # production emits: from = config path, specifier empty,
        # reason CONFIG_UNREADABLE), so the audit is INCOMPLETE
        # instead of quietly PASSing over a hole in the tree. The
        # entries fire whether or not any import used the config: the
        # unknown config is itself the hole.
        if self.tsconfig_status in ("UNREADABLE", "MALFORMED"):
            unknown.append({"from": "tsconfig.json", "specifier": "",
                            "reason": CONFIG_UNREADABLE_REASON,
                            "line": 1})
        if self.pkg_status in ("UNREADABLE", "MALFORMED"):
            unknown.append({"from": "package.json", "specifier": "",
                            "reason": CONFIG_UNREADABLE_REASON,
                            "line": 1})
        for rel in self.files:
            full = os.path.join(self.repo_root, rel)
            try:
                data = open(full, "rb").read()
            except PermissionError:
                # FIX P024 R1 P1-01: a listed-but-unreadable file is a
                # module whose imports are UNKNOWN, not a file that
                # does not exist. It stays in the ground truth with
                # parseStatus UNREADABLE and an empty content hash
                # (the content is unknown, never guessed) -- mirroring
                # production (src/extractors/typescript/index.ts) --
                # so the audit is INCOMPLETE instead of crashing the
                # Oracle or quietly PASSing over a hole.
                is_decl = rel.endswith(".d.ts")
                modules.append({
                    "relativePath": rel,
                    "moduleId": module_id("typescript", rel),
                    "contentSha256": "",
                    "language": "typescript",
                    "nodeKind": "module",
                    "isGenerated": False,
                    "isEntrypoint": rel in self.entrypoints,
                    "parseStatus": "UNREADABLE",
                    "isDeclarationFile": is_decl,
                    "files": [{"relativePath": rel, "contentSha256": "",
                               "isGenerated": False, "isCgo": False}],
                })
                continue
            content_sha = sha256_hex(data)
            generated = False
            parse_status = "OK"
            if len(data) > MAX_FILE_BYTES:
                parse_status = "TOO_LARGE"
                text = None
            else:
                try:
                    text = data.decode("utf-8")
                except UnicodeDecodeError:
                    parse_status = "PARSE_ERROR"
                    text = None
                else:
                    generated = is_generated_content(text)
                    if not balanced(text):
                        parse_status = "PARSE_ERROR"
            is_decl = rel.endswith(".d.ts")
            modules.append({
                "relativePath": rel,
                "moduleId": module_id("typescript", rel),
                "contentSha256": content_sha,
                "language": "typescript",
                "nodeKind": "module",
                "isGenerated": generated,
                "isEntrypoint": rel in self.entrypoints,
                "parseStatus": parse_status,
                "isDeclarationFile": is_decl,
                "files": [{"relativePath": rel, "contentSha256": content_sha,
                           "isGenerated": generated, "isCgo": False}],
            })
            if parse_status != "OK":
                continue
            n_ext, stmts = self._extract_file(
                rel, text, is_decl, generated, edges, generated_edges,
                unknown)
            external_count += n_ext
        edge_list = sorted(edges.values(),
                           key=lambda e: (e["from"], e["to"], e["evidence"]["line"]))
        gen_list = sorted(generated_edges.values(),
                          key=lambda e: (e["from"], e["to"], e["evidence"]["line"]))
