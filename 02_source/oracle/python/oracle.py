def run_fixture(fixture_dir):
    """Run the Oracle on one fixture dir (contains repo/, claimed-map.json).
    Returns the canonical output dict. Never reads golden.json."""
    fixture_dir = os.path.abspath(fixture_dir)
    name = os.path.basename(fixture_dir)
    repo = os.path.join(fixture_dir, "repo")
    with open(os.path.join(fixture_dir, "claimed-map.json"),
              "r", encoding="utf-8") as fh:
        claimed = json.load(fh)
    language = None
    # Language is inferred from the fixture name prefix (py-/ts-/go-),
    # which is part of the frozen fixture layout -- not from golden.json.
    if name.startswith("py-"):
        language = "python"
    elif name.startswith("ts-"):
        language = "typescript"
    elif name.startswith("go-"):
        language = "go"
    else:
        raise ValueError(f"cannot infer language for fixture {name!r}")
    if language == "python":
        oracle = PythonOracle(repo)
    elif language == "typescript":
        oracle = TypeScriptOracle(repo)
    else:
        oracle = GoOracle(repo)
    gt = oracle.extract()
    # FIX T013 (P1-01): hand the audit the literal toml entrypoint
    # spellings too (Go: file paths such as "cmd/server/main.go").
    # The ground-truth dict itself is unchanged, so the S0 gate hash
    # (which hashes the full Oracle output) is unaffected.
    audit = audit_claimed_map(
        gt, claimed,
        declared_literal_entrypoints=getattr(
            oracle, "entrypoint_literal_paths", None))
    return {"fixture": name, "language": language, "seed": SEED,
            "groundTruth": gt, "audit": audit}


def canonical_json(obj):
    return json.dumps(obj, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False)


def main(argv=None):
    ap = argparse.ArgumentParser(description="P024 independent Oracle (T004)")
    ap.add_argument("--fixture-dir", help="single fixture directory")
    ap.add_argument("--fixtures-root",
                    help="directory containing py-*/ts-*/go-* fixtures")
    ap.add_argument("--replay", type=int, default=0,
                    help="run all fixtures N times; emit per-replay hashes")
    ap.add_argument("--out", required=True, help="output JSON path")
    args = ap.parse_args(argv)
    if args.fixture_dir:
        result = run_fixture(args.fixture_dir)
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(canonical_json(result) + "\n")
        return 0
    if not args.fixtures_root:
        ap.error("need --fixture-dir or --fixtures-root")
    names = []
    for lang_dir in ("python", "typescript", "go"):
        sub = os.path.join(args.fixtures_root, lang_dir)
        if not os.path.isdir(sub):
            continue
        for d in sorted(os.listdir(sub)):
            full = os.path.join(sub, d)
            if d.startswith(("py-", "ts-", "go-")) and os.path.isdir(full):
                names.append(os.path.join(lang_dir, d))
    if args.replay:
        hashes = []
        for _ in range(args.replay):
            results = [run_fixture(os.path.join(args.fixtures_root, n))
                       for n in names]
            hashes.append(sha256_hex(canonical_json(results)))
        out = {"replays": hashes, "distinct": len(set(hashes)),
               "hash": hashes[0] if len(set(hashes)) == 1 else None,
               "replayCount": args.replay, "fixtureCount": len(names)}
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(canonical_json(out) + "\n")
        return 0
    results = [run_fixture(os.path.join(args.fixtures_root, n)) for n in names]
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(canonical_json({"fixtures": results}) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
