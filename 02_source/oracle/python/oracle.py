def _dotted_of(rel, search_root_rel):
    """Dotted module name of file `rel` (repo-relative) under search root
    `search_root_rel` ("" for repo root, "src" for src layout), or None if
    the file is not under that root. __init__.py maps to its package."""
    if search_root_rel:
        if rel != search_root_rel and not rel.startswith(search_root_rel + "/"):
            return None
        sub = rel[len(search_root_rel) + 1:]
    else:
        sub = rel
    if not sub.endswith(".py"):
        return None
    sub = sub[:-3]
    if sub.endswith("/__init__"):
        sub = sub[: -len("/__init__")]
    elif sub == "__init__":
        return ""  # repo-root __init__: no dotted name; not indexed
    parts = sub.split("/")
    return ".".join(parts)


def _ancestors_have_init(repo_root, search_root_rel, dotted):
    """Package-boundary rule: every proper ancestor package directory of
    `dotted` must contain __init__.py (relative to the search root)."""
    parts = dotted.split(".") if dotted else []
    for i in range(1, len(parts)):
        pkg_dir = "/".join(parts[:i])
        base = f"{search_root_rel}/{pkg_dir}" if search_root_rel else pkg_dir
        if not os.path.exists(os.path.join(repo_root, base, "__init__.py")):
            return False
    return True


class PythonOracle:
    def __init__(self, repo_root):
        self.repo_root = repo_root
        # FIX P024 R1 P1-01: directories that could not be listed
        # (their contents are UNKNOWN); mirrored by the production
        # extractors, which record the same paths.
        self.files, self.unreadable_dirs = \
            list_repo_files_detailed(repo_root)
        self.files = [f for f in self.files if f.endswith(".py")]
        self.search_roots = [""] + (["src"] if os.path.isdir(
            os.path.join(repo_root, "src")) else [])
        # dotted name -> relative path (first search root wins; identical
        # files under both roots keep the repo-root mapping only if valid)
        self.module_index = {}
        for rel in self.files:
            for root_rel in self.search_roots:
                dotted = _dotted_of(rel, root_rel)
                if dotted is None or dotted == "":
                    continue
                if not _ancestors_have_init(repo_root, root_rel, dotted):
                    continue
                # Prefer the shorter (src-layout) mapping only when the
                # repo-root mapping is absent; both are valid names, but
                # an import resolves to exactly one file per dotted name.
                if dotted not in self.module_index:
                    self.module_index[dotted] = rel
        # Top-level names that exist anywhere repo-local (for the
        # external-vs-UNRESOLVABLE_REPO_LOCAL split, T002 rule).
        self.repo_local_toplevel = set()
        for rel in self.files:
            for root_rel in self.search_roots:
                dotted = _dotted_of(rel, root_rel)
                if dotted:
                    self.repo_local_toplevel.add(dotted.split(".")[0])
        try:
            self.entrypoints = parse_entrypoints_toml(repo_root)
            self.entrypoints_declaration_unreadable = False
        except EntrypointsTomlUnreadableError:
            # FIX P024 R1 P1-01 follow-up: the declaration is UNKNOWN,
            # not absent — the audit must force INCOMPLETE (see
            # audit_claimed_map), never audit as if nothing was
            # declared. The toml file itself is still recorded
            # UNREADABLE by the snapshot marker.
            self.entrypoints = []
            self.entrypoints_declaration_unreadable = True
        # FIX T013 (P1-01): literal toml spellings. For Python the
        # declaration already is file paths, so these equal
        # self.entrypoints; kept for the uniform audit interface.
        self.entrypoint_literal_paths = list(self.entrypoints)
        # FIX T013 R4 (R4-P1-01): literal declarations that resolve to
        # no module; filled in by extract() (see _resolve_declared_
        # entrypoints). Mirrors production built.unresolvedEntrypoints.
        self.unresolved_entrypoints = []

    def _resolve_absolute(self, dotted):
        """Resolve an absolute dotted name to a repo-relative .py path."""
        return self.module_index.get(dotted)

    def extract(self):
        modules = []
        edges = {}          # (from, to) -> edge dict (first occurrence)
        generated_edges = {}
        external = []       # {from, specifier, line, conditional}
        unknown = []        # {from, specifier, reason, line}
        dynamic = []        # {path, line, statement, kind}
        # FIX P024 R1 P1-01: directories that could not be listed hold
        # UNKNOWN content (possibly .py files). Each becomes an
        # UNREADABLE unknown with the identical shape production emits
        # (same from/specifier/reason/line/statement), so the two
        # verdicts agree.
        for d in self.unreadable_dirs:
            unknown.append({"from": d, "specifier": "",
                            "reason": "UNREADABLE", "line": 1,
                            "statement": f'directory "{d}" could not be '
                            "listed; its contents are unknown"})
        for rel in self.files:
            full = os.path.join(self.repo_root, rel)
            try:
                data = open(full, "rb").read()
            except PermissionError:
                # FIX P024 R1 P1-01: a listed-but-unreadable file is a
                # module whose imports are UNKNOWN, not a file that
                # does not exist. It stays in the ground truth with
                # parseStatus UNREADABLE and an empty content hash
                # (the content is unknown, never guessed) -- mirroring
                # production (src/extractors/python/index.ts) -- so
                # the audit is INCOMPLETE instead of crashing the
                # Oracle or quietly PASSing over a hole.
                modules.append({
                    "relativePath": rel,
                    "moduleId": module_id("python", rel),
                    "contentSha256": "",
                    "language": "python",
                    "nodeKind": "module",
                    "isGenerated": False,
                    "isEntrypoint": rel in self.entrypoints,
                    "parseStatus": "UNREADABLE",
                    "files": [{"relativePath": rel, "contentSha256": "",
                               "isGenerated": False, "isCgo": False}],
                })
                continue
            content_sha = sha256_hex(data)
            generated = False
            parse_status = "OK"
            if len(data) > MAX_FILE_BYTES:
                parse_status = "TOO_LARGE"
                text = None
            else:
                try:
                    text = data.decode("utf-8")
                except UnicodeDecodeError:
                    parse_status = "PARSE_ERROR"
                    text = None
                else:
                    generated = is_generated_content(text)
                    try:
                        tree = ast.parse(text)
                    except SyntaxError:
                        parse_status = "PARSE_ERROR"
                        tree = None
            modules.append({
                "relativePath": rel,
                "moduleId": module_id("python", rel),
                "contentSha256": content_sha,
                "language": "python",
                "nodeKind": "module",
                "isGenerated": generated,
                "isEntrypoint": rel in self.entrypoints,
                "parseStatus": parse_status,
                "files": [{"relativePath": rel, "contentSha256": content_sha,
                           "isGenerated": generated, "isCgo": False}],
            })
            if parse_status != "OK":
                continue
            self._extract_file(rel, text, tree, generated, edges,
                               generated_edges, external, unknown, dynamic)
        edge_list = sorted(edges.values(),
                           key=lambda e: (e["from"], e["to"], e["evidence"]["line"]))
        gen_list = sorted(generated_edges.values(),
                          key=lambda e: (e["from"], e["to"], e["evidence"]["line"]))
        # FIX T013 R4 (R4-P1-01): resolve the declared entrypoints
        # against the extracted modules, mirroring production
        # (src/graph/build.ts). self.entrypoints becomes the RESOLVED
        # module paths only -- the production ground truth's
        # `entrypoints` list -- so a declared file that does not exist
        # (e.g. "ghost.py") drops out of the GT instead of being listed
        # as an entrypoint, and self.unresolved_entrypoints records the
        # literal spelling(s) that did not resolve. isEntrypoint flags
        # are recomputed from the resolved set (a real module named by
        # a literal declaration is resolved by exact match, so flags
        # are unchanged for resolvable declarations); reachability
        # below then BFSes from the resolved entrypoints only.
        resolved, unresolved = _resolve_declared_entrypoints(
            self.entrypoint_literal_paths, modules)
        self.entrypoints = resolved
        self.unresolved_entrypoints = unresolved
        resolved_set = set(resolved)
        for m in modules:
            m["isEntrypoint"] = m["relativePath"] in resolved_set
        gt = {
            "modules": sorted(modules, key=lambda m: m["relativePath"]),
            "edges": edge_list,
            "generatedEdges": gen_list,
            "entrypoints": sorted(self.entrypoints),
            "externalImportCount": len(external),
            "externalImports": sorted(
                external, key=lambda x: (x["from"], x["specifier"], x["line"])),
            "unknownImports": sorted(
                unknown, key=lambda x: (x["from"], x["specifier"], x["line"])),
            "dynamicUnknown": sorted(
                dynamic, key=lambda x: (x["path"], x["line"])),
            "excludedFiles": [],
        }
        gt["reachableFromEntrypoints"], gt["isolatedModules"] = \
            self._reachability(gt["modules"], gt["edges"])
        gt["repoSnapshotSha256"] = snapshot_sha256(self.repo_root)
        # FIX P024 R1 P1-01 follow-up: an unreadable entrypoint
        # declaration is UNKNOWN, not absent — record it ONLY when
        # true so the S0 gate hash is unchanged on readable fixtures.
        if self.entrypoints_declaration_unreadable:
            gt["entrypointsDeclarationUnreadable"] = True
        return gt

    def _reachability(self, modules, edges):
        """BFS from entrypoints over core edges + package-init closure:
        importing a submodule executes its ancestor __init__.py files, so
        they count as reachable (no extra edges)."""
        by_path = {m["relativePath"]: m for m in modules}
        out = {}
        for e in edges:
            out.setdefault(e["from"], []).append(e["to"])
        reachable = set()
        stack = list(self.entrypoints)
        while stack:
            cur = stack.pop()
            if cur in reachable or cur not in by_path:
                continue
            reachable.add(cur)
            # ancestor __init__.py files of cur
            parts = cur.split("/")[:-1]
            for i in range(len(parts), 0, -1):
                init = "/".join(parts[:i]) + "/__init__.py"
                if init in by_path and init not in reachable:
                    stack.append(init)
            for nxt in out.get(cur, []):
                if nxt not in reachable:
                    stack.append(nxt)
        isolated = sorted(p for p in by_path if p not in reachable)
        return sorted(reachable), isolated

    # -- per-file extraction ---------------------------------------------
    def _extract_file(self, rel, text, tree, generated, edges, gen_edges,
                      external, unknown, dynamic):
        dotted = self._dotted_of_file(rel)
        # package of this module: __init__ -> its own dotted name,
        # otherwise dotted minus last component.
        if rel.endswith("/__init__.py") or rel == "__init__.py":
            package_parts = dotted.split(".") if dotted else []
        else:
            package_parts = dotted.split(".")[:-1] if dotted else []

        def add_edge(target_rel, line, statement, conditional, type_only):
            if target_rel == rel:
                return  # __init__ self-edge: skip
            rec = {"from": rel, "to": target_rel, "conditional": conditional,
                   "typeOnly": type_only,
                   "evidence": {"line": line, "statement": statement,
                                "specifier": None, "file": None},
                   "kind": None}
            bucket = gen_edges if generated else edges
            key = (rel, target_rel)
            if key not in bucket:
                bucket[key] = rec

        def classify_absolute(dotted_name, line, statement, conditional,
                              type_only):
            """Resolve an absolute dotted import; record edge, external or
            unknown. Returns the resolved file path or None."""
            target = self._resolve_absolute(dotted_name)
            if target is not None:
                add_edge(target, line, statement, conditional, type_only)
                return target
            top = dotted_name.split(".")[0]
            if top in self.repo_local_toplevel:
                unknown.append({"from": rel, "specifier": dotted_name,
                                "reason": "UNRESOLVABLE_REPO_LOCAL",
                                "line": line, "statement": statement})
            else:
                external.append({"from": rel, "specifier": dotted_name,
                                 "line": line, "conditional": conditional})
            return None

        def resolve_from_import(module_dotted, names, node, conditional,
                               type_only):
            """from M import c: edge to M, plus edge to M.c when M.c is a
            real module file (c is an attribute otherwise)."""
            line = node.lineno
            statement = ast.get_source_segment(text, node) or ""
            statement = " ".join(statement.split())
            classify_absolute(module_dotted, line, statement, conditional,
                              type_only)
            for alias in names:
                if alias.name == "*":
                    continue
                sub = f"{module_dotted}.{alias.name}" if module_dotted \
                    else alias.name
                target = self._resolve_absolute(sub)
                if target is not None:
                    add_edge(target, line, statement, conditional, type_only)

        def visit(node, in_try, in_type_checking):
            conditional = in_try or in_type_checking
            if isinstance(node, ast.Import):
                statement = " ".join(
                    (ast.get_source_segment(text, node) or "").split())
                for alias in node.names:
                    classify_absolute(alias.name, node.lineno, statement,
                                      conditional, in_type_checking)
            elif isinstance(node, ast.ImportFrom):
                level = node.level or 0
                if level == 0:
                    base = node.module or ""
                    resolve_from_import(base, node.names, node, conditional,
                                      in_type_checking)
                else:
                    # relative: base = package minus (level-1) components
                    if not package_parts:
                        unknown.append({
                            "from": rel,
                            "specifier": (node.module or ""),
                            "reason": "RELATIVE_NO_PACKAGE",
                            "line": node.lineno,
                            "statement": " ".join(
                                (ast.get_source_segment(text, node)
                                 or "").split())})
                        return
                    if level - 1 > len(package_parts):
                        unknown.append({
                            "from": rel,
                            "specifier": (node.module or ""),
                            "reason": "RELATIVE_ESCAPE",
                            "line": node.lineno,
                            "statement": " ".join(
                                (ast.get_source_segment(text, node)
                                 or "").split())})
                        return
                    base_parts = package_parts[:len(package_parts) - (level - 1)]
                    base = ".".join(base_parts + ([node.module] if node.module else []))
                    resolve_from_import(base, node.names, node, conditional,
                                      in_type_checking)
            elif isinstance(node, ast.Call):
                self._visit_dynamic(node, rel, text, dynamic,
                                    classify_absolute, conditional,
                                    in_type_checking)
            for child in ast.iter_child_nodes(node):
                child_try = in_try
                child_tc = in_type_checking
                if isinstance(node, (ast.Try, ast.TryStar)):
                    child_try = True
                elif isinstance(node, ast.If) and self._is_type_checking(node.test):
                    child_tc = True
                visit(child, child_try, child_tc)

        visit(tree, False, False)

    @staticmethod
    def _is_type_checking(test):
        if isinstance(test, ast.Name) and test.id == "TYPE_CHECKING":
            return True
        if (isinstance(test, ast.Attribute) and test.attr == "TYPE_CHECKING"
                and isinstance(test.value, ast.Name)
                and test.value.id == "typing"):
            return True
        return False

    def _visit_dynamic(self, node, rel, text, dynamic, classify_absolute,
                       conditional=False, type_only=False):
        """importlib.import_module(x) / __import__(x) / exec/eval with an
        import string. Literal argument resolves as a normal absolute
        import; a variable argument is DYNAMIC_IMPORT_UNKNOWN."""
        func = node.func
        seg = ast.get_source_segment(text, node) or ""
        seg = " ".join(seg.split())
        target_arg = None
        kind = None
        if (isinstance(func, ast.Attribute) and func.attr == "import_module"
                and isinstance(func.value, ast.Name)
                and func.value.id == "importlib"):
            kind = "IMPORTLIB_VARIABLE"
        elif isinstance(func, ast.Name) and func.id == "__import__":
            kind = "DUNDER_IMPORT_VARIABLE"
        elif isinstance(func, ast.Name) and func.id in ("exec", "eval"):
            if node.args and isinstance(node.args[0], ast.Constant) \
                    and isinstance(node.args[0].value, str) \
                    and "import" in node.args[0].value:
                dynamic.append({"path": rel, "line": node.lineno,
                                "statement": seg, "kind": "EXEC_EVAL_IMPORT"})
            return
        else:
            return
        if not node.args:
            return
        arg = node.args[0]
        if isinstance(arg, ast.Constant) and isinstance(arg.value, str):
            # literal: resolves like a normal absolute import
            classify_absolute(arg.value, node.lineno, seg, conditional,
                              type_only)
        else:
            dynamic.append({"path": rel, "line": node.lineno,
                            "statement": seg, "kind": kind})

    def _dotted_of_file(self, rel):
        for root_rel in self.search_roots:
            dotted = _dotted_of(rel, root_rel)
            if dotted is not None and dotted != "":
                if _ancestors_have_init(self.repo_root, root_rel, dotted):
                    return dotted
        return ""


