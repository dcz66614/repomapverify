def normalize_rel(path):
    """Frozen path normalization (contracts/module.ts): NFC, backslash->slash,
    strip leading ./ and empty segments."""
    p = unicodedata.normalize("NFC", path).replace("\\", "/")
    parts = [s for s in p.split("/") if s not in ("", ".")]
    return "/".join(parts)


def sha256_hex(data):
    if isinstance(data, str):
        data = data.encode("utf-8")
    return hashlib.sha256(data).hexdigest()


def module_id(language, normalized_path):
    """module_id = SHA256(language + NUL + normalized path)."""
    return sha256_hex(language + "\0" + normalized_path)


def go_package_hash(files):
    """Go package content hash: SHA256 over sorted
    `relativePath + NUL + contentSha256 + "\\n"` lines."""
    body = "".join(
        f"{f['relativePath']}\0{f['contentSha256']}\n"
        for f in sorted(files, key=lambda x: x["relativePath"])
    )
    return sha256_hex(body)


def is_generated_content(text):
    head = "\n".join(text.split("\n")[:5])
    return any(m in head for m in GENERATED_MARKERS)


def list_repo_files_detailed(repo_root, skip_extra=frozenset()):
    """Like list_repo_files, but also returns the directories that
    could not be listed at all.

    Returns (files, unreadable_dirs): files are the POSIX relative
    paths (sorted), unreadable_dirs are the repo-relative paths of
    directories whose listing failed (e.g. unreadable, EACCES),
    sorted, with the repo root itself reported as "." when it cannot
    be listed. Their contents are UNKNOWN -- they must never be
    treated as "no files here" (PROJECT_BOOK section 5.1, "跳过项转
    finding"; FIX P024 R1 P1-01).

    os.walk silently ignores scandir errors by default, so the
    failure is captured with an onerror handler: without it an
    unreadable subdirectory (and everything in it) vanished without
    a trace and the audit could PASS over an incomplete tree."""
    skip = SKIP_DIRS | set(skip_extra)
    out = []
    unreadable = []

    def _onerror(err):
        filename = getattr(err, "filename", None)
        if filename is None:
            return
        rel = normalize_rel(os.path.relpath(filename, repo_root))
        unreadable.append(rel if rel != "" else ".")

    for dirpath, dirnames, filenames in os.walk(repo_root,
                                                onerror=_onerror):
        dirnames[:] = sorted(d for d in dirnames if d not in skip)
        for fn in sorted(filenames):
            full = os.path.join(dirpath, fn)
            out.append(normalize_rel(os.path.relpath(full, repo_root)))
    return sorted(out), sorted(unreadable)


def list_repo_files(repo_root, skip_extra=frozenset()):
    """All files under repo_root (POSIX relative paths, sorted), skipping
    .git / node_modules / __pycache__ / .venv / venv (+ caller extras).

    FIX T013 R2 (R2-P1-01): ".venv" and "venv" added so this set matches
    production exactly -- the Python extractor
    (src/extractors/python/index.ts EXCLUDED_DIRS) and the snapshot scan
    (src/graph/fromRepo.ts SNAPSHOT_EXCLUDED_DIRS + DEFAULT_EXCLUDED_DIRS).
    list_repo_files feeds BOTH module enumeration and snapshot_sha256, so
    a name missing here diverges on both at once (production PASS vs
    Oracle INCOMPLETE on a repo with a venv/ dir)."""
    files, _unreadable = list_repo_files_detailed(repo_root, skip_extra)
    return files


def _snapshot_sort_key(path):
    """Sort key mirroring production compareNormalizedPaths
    (src/identity/normalize.ts): NFC-normalized path first, then plain
    code-unit order."""
    nfc = unicodedata.normalize("NFC", path)
    return (nfc, path)


def snapshot_sha256(repo_root):
    """Frozen snapshot algorithm (T008): SHA256 over sorted
    `relativePath + NUL + contentSha256 + "\\n"` lines for every file
    under the repo root (excluding .git / node_modules / __pycache__ /
    .venv / venv).

    FIX T013 (P1-03): the lines are over PHYSICAL files, exactly like
    production computeRepoSnapshotSha256 (src/graph/fromRepo.ts, via
    groupByRealPath): in-repo symlink spellings of one file collapse
    to the canonical (smallest normalized) path, so one physical file
    contributes exactly one line. Symlinks whose target resolves
    OUTSIDE the repo, and broken symlinks, contribute no line at all
    (production never follows them). On symlink-free repos this is
    identical to listing every spelling, so all 48 S0 fixtures hash
    exactly as before."""
    root_real = os.path.realpath(repo_root)
    by_real = {}  # realpath -> [repo-relative spellings]
    _files, unreadable_dirs = list_repo_files_detailed(repo_root)
    for rel in _files:
        full = os.path.join(repo_root, rel)
        try:
            real = os.path.realpath(full)
        except OSError:
            continue
        if real != root_real and not real.startswith(root_real + os.sep):
            continue  # outside-repo target: never followed, never listed
        if not os.path.exists(real):
            continue  # broken symlink: never guessed
        by_real.setdefault(real, []).append(rel)
    lines = []
    for real in sorted(by_real):
        canonical = min(by_real[real], key=_snapshot_sort_key)
        # FIX P024 R1 P1-01: an unreadable file is UNKNOWN content,
        # not an absent file. It contributes a marker line
        # `path + NUL + "UNREADABLE" + "\n"` (identical format to
        # production's computeRepoSnapshotSha256 in
        # src/extractors/python/index.ts and src/graph/fromRepo.ts)
        # instead of crashing the Oracle with PermissionError or
        # silently hashing as if the file did not exist.
        try:
            with open(os.path.join(repo_root, canonical), "rb") as fh:
                content = fh.read()
        except PermissionError:
            lines.append(f"{canonical}\0UNREADABLE\n")
            continue
        lines.append(f"{canonical}\0{sha256_hex(content)}\n")
    # FIX P024 R1 P1-01: directories that could not be listed hold
    # UNKNOWN content (possibly source files). Each contributes the
    # same UNREADABLE marker line, so the hash of an incompletely
    # scanned tree can never quietly equal the hash of a tree that
    # genuinely lacks those paths.
    for d in unreadable_dirs:
        lines.append(f"{d}\0UNREADABLE\n")
    lines.sort()
    return sha256_hex("".join(lines))


def _resolve_declared_entrypoints(literal_paths, modules):
    """Resolve declared entrypoint paths against a module set, mirroring
    production resolveEntrypoint (src/graph/build.ts).

    Production resolution order, per literal (already normalized) path:
      1. exact match against a python/typescript module path;
      2. otherwise the path's parent directory against a go package
         module (a Go entrypoint is a file inside its package dir; a
         root file maps to ".").
    Returns (resolved_module_paths, unresolved_literal_paths):
    resolved are the module paths the declarations map to (deduped,
    sorted -- the production ground truth's `entrypoints` list);
    unresolved are the literal toml spellings that resolve to no module
    (sorted with the production compareNormalizedPaths order), i.e.
    production's built.unresolvedEntrypoints. A literal that names a Go
    package directory directly (e.g. "cmd/server" with no file) does
    NOT resolve: step 1 needs a python/typescript module of that path
    and step 2 looks up its parent ("cmd"), exactly like production.
    """
    module_keys = {(m["language"], m["relativePath"]) for m in modules}
    resolved, unresolved, seen = [], [], set()
    for lit in literal_paths:
        target = None
        if ("python", lit) in module_keys or ("typescript", lit) in module_keys:
            target = lit
        else:
            parent = "/".join(lit.split("/")[:-1]) or "."
            if ("go", parent) in module_keys:
                target = parent
        if target is None:
            unresolved.append(lit)
        elif target not in seen:
            seen.add(target)
            resolved.append(target)
    return sorted(resolved), sorted(unresolved, key=_snapshot_sort_key)


class EntrypointsTomlUnreadableError(OSError):
    """`.repomapverify.toml` exists but could not be read: the
    entrypoint declaration is UNKNOWN, not absent (fail-closed, FIX
    P024 R1 P1-01 follow-up). Callers catch this and record the
    declaration as unreadable so the audit forces INCOMPLETE."""


def parse_entrypoints_toml(repo_root):
    """Minimal parser for .repomapverify.toml: [entrypoints] paths = [...].
    Absent file -> []. Malformed -> raises ValueError (never guessed).
    Unreadable file -> raises EntrypointsTomlUnreadableError (FIX P024
    R1 P1-01 follow-up): the declaration is UNKNOWN, not absent, so
    callers must NOT fall back to "no declaration" — that path can
    PASS via ENTRYPOINT_CANDIDATE. (P1-01 returned [] here, the same
    fallback the production extractors use; the file itself is still
    recorded UNREADABLE by the snapshot marker, so the audit cannot
    quietly PASS over it — but the snapshot alone cannot distinguish
    "no declaration" from "unknown declaration", hence the
    exception.) Any read failure counts, not just PermissionError:
    production treats any read error the same way."""
    path = os.path.join(repo_root, ".repomapverify.toml")
    if not os.path.exists(path):
        return []
    try:
        with open(path, "r", encoding="utf-8") as fh:
            text = fh.read()
    except OSError as exc:
        raise EntrypointsTomlUnreadableError(
            f"cannot read {path}: {exc}") from exc
    if text.strip() == "":
        return []
    in_section = False
    seen = False
    paths = None
    for raw in text.splitlines():
        # strip comments outside quotes
        line = ""
        quote = None
        for ch in raw:
            if quote is not None:
                line += ch
                if ch == quote:
                    quote = None
            elif ch in ("\"", "'"):
                quote = ch
                line += ch
            elif ch == "#":
                break
            else:
                line += ch
        line = line.strip()
        if not line:
            continue
        m = re.match(r"^\[([A-Za-z0-9_.\-]+)\]$", line)
        if m:
            if m.group(1) == "entrypoints":
                if seen:
                    raise ValueError("duplicate [entrypoints] section")
                seen = True
                in_section = True
            else:
                raise ValueError(f"unsupported section [{m.group(1)}]")
            continue
        if not in_section:
            raise ValueError(f"key outside [entrypoints]: {line}")
        m = re.match(r"^paths\s*=\s*(.+)$", line)
        if not m:
            raise ValueError(f"unsupported key in [entrypoints]: {line}")
        if paths is not None:
            raise ValueError("duplicate paths key")
        arr = m.group(1).strip()
        if not (arr.startswith("[") and arr.endswith("]")):
            raise ValueError("paths must be an array")
        inner = arr[1:-1].strip()
        paths = []
        if inner:
            for tok in re.findall(r'"([^"]*)"|\'([^\']*)\'', inner):
                paths.append(tok[0] if tok[1] == "" else tok[1])
    if not seen:
        raise ValueError("missing [entrypoints] section")
    if paths is None:
        raise ValueError("missing paths key in [entrypoints]")
    return [normalize_rel(p) for p in paths]


def strip_comments(text):
    """Remove // line comments and /* */ block comments, respecting
    '...' "..." `...` strings (with backslash escapes). Returns text
    with comments replaced by spaces (newlines preserved)."""
    out = []
    i, n = 0, len(text)
    state = None  # None | "line" | "block" | "'" | '"' | "`"
    while i < n:
        ch = text[i]
        nxt = text[i + 1] if i + 1 < n else ""
        if state is None:
            if ch == "/" and nxt == "/":
                state = "line"
                out.append("  ")
                i += 2
            elif ch == "/" and nxt == "*":
                state = "block"
                out.append("  ")
                i += 2
            elif ch in ("'", '"', "`"):
                state = ch
                out.append(ch)
                i += 1
            else:
                out.append(ch)
                i += 1
        elif state == "line":
            if ch == "\n":
                state = None
                out.append(ch)
            else:
                out.append(" ")
            i += 1
        elif state == "block":
            if ch == "*" and nxt == "/":
                state = None
                out.append("  ")
                i += 2
            else:
                out.append("\n" if ch == "\n" else " ")
                i += 1
        else:  # inside a string
            out.append(ch)
            if ch == "\\":
                if i + 1 < n:
                    out.append(text[i + 1])
                    i += 2
                else:
                    i += 1
            elif ch == state:
                state = None
                i += 1
            else:
                i += 1
    return "".join(out)


def balanced(text):
    """Cheap syntax sanity proxy for the regex parsers (TS/Go): braces,
    parens and brackets must balance outside strings/comments. All S0
    fixtures are balanced; an unbalanced file is PARSE_ERROR, never
    silently trusted."""
    code = strip_comments(text)
    # remove string contents (keep quotes structure out of the count)
    code = re.sub(r"'(?:\\.|[^'\\])*'", "''", code)
    code = re.sub(r'"(?:\\.|[^"\\])*"', '""', code)
    code = re.sub(r"`(?:\\.|[^`\\])*`", "``", code)
    stack = []
    pairs = {")": "(", "]": "[", "}": "{"}
    for ch in code:
        if ch in "([{":
            stack.append(ch)
        elif ch in ")]}":
            if not stack or stack[-1] != pairs[ch]:
                return False
            stack.pop()
    return not stack


