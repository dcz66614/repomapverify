FAIL_FINDING_IDS = {"HALLUCINATED_EDGE", "HALLUCINATED_MODULE",
                    "WRONG_ENTRYPOINT", "MISSING_EDGE",
                    "UNCLAIMED_REACHABLE_MODULE", "NAME_COLLISION_CONFUSION"}


def _resolve_claimed_snapshot(claimed):
    """Mirror the production validator alias rule
    (src/io/validate-claimed-map.ts resolveAliasedStringField): the
    camelCase key wins; the snake_case alias is accepted; both
    spellings present with DIFFERENT values is a conflict. The audit
    has no validation-error channel (production rejects such a map
    with exit 3), so a conflict reads here as a snapshot mismatch.
    Returns (value_or_None, conflict_bool)."""
    camel = claimed.get("repoSnapshotSha256")
    snake = claimed.get("repo_snapshot_sha256")
    if camel is not None and snake is not None and camel != snake:
        return None, True
    return (camel if camel is not None else snake), False


def audit_claimed_map(gt, claimed, declared_literal_entrypoints=None):
    """Returns {"status", "snapshotStatus", "findings",
    "unknownImportsPresent"}. Rules (spec section 5):
      * HALLUCINATED_EDGE: claimed edge absent from real edges (even when
        an endpoint module does not exist).
      * HALLUCINATED_MODULE: claimed module absent from real modules.
      * WRONG_ENTRYPOINT: claimed entrypoint not in the .repomapverify.toml
        declaration -- only when the declaration is non-empty. A
        declared entrypoint is accepted in BOTH spellings (FIX T013,
        P1-01): the ground-truth path (Go: package dir) and the
        literal toml spelling (e.g. "cmd/server/main.go"), exactly
        like production (src/comparator/compare.ts Rule 4).
      * GENERATED_MISMATCH (module-level, P2, never flips the verdict;
        FIX T013, P2-01): a claimed module asserting generated true/false
        whose ground-truth isGenerated disagrees. Absent assertion means
        no judgement, per the T008 decision record.
      * Snapshot binding (FIX T013, P1-02): the claimed snapshot hash
        is resolved with the production alias rule -- camelCase wins,
        snake_case repo_snapshot_sha256 accepted, conflicting spellings
        read as a mismatch.
      * Stale snapshot short-circuit (FIX T013 R3, R3-P1-01): when the
        resolved snapshot status is STALE_SNAPSHOT (including the
        snapshot-conflict case), the audit returns INCOMPLETE with an
        EMPTY findings list -- mirroring production Rule 1
        (src/comparator/compare.ts:283-293) exactly. The map describes
        a different tree, so none of its errors may be blamed on the
        agent (PROJECT_BOOK section 5.1). unknownImportsPresent is
        still computed from ground truth in that branch: it is a fact
        about the current tree, not a blame finding on the map.
      * Unresolvable declared entrypoint (FIX T013 R4, R4-P1-01):
        a toml-declared entrypoint that resolves to no module in the
        ground truth -- mirroring production Rule 9
        (src/comparator/compare.ts:507,518-521, hasUnresolvedEntrypoints
        from src/graph/build.ts) -- forces INCOMPLETE with status only:
        no finding is emitted (the declaration is accepted as written,
        so no WRONG_ENTRYPOINT fires for it, exactly like production).
        The literal spelling(s) are recorded in the returned audit dict
        as `unresolvedEntrypoints` (mirroring production's
        built.unresolvedEntrypoints). The field is present ONLY when
        non-empty: all 48 S0 fixtures resolve every declaration, so
        omitting it there keeps the S0 gate hash unchanged. When no
        literal declarations are handed in (declared_literal_
        entrypoints is None) the unresolved list cannot be known --
        the GT `entrypoints` are already the resolved list -- and it
        is reported as empty.
      * Unreadable entrypoint declaration (FIX P024 R1 P1-01
        follow-up): `.repomapverify.toml` exists but could not be read
        (gt `entrypointsDeclarationUnreadable`) -- the declaration is
        UNKNOWN, not absent, so entrypoints cannot be verified and
        the audit is INCOMPLETE with status only, mirroring production
        compare.ts Rule 7/9 and the S0 gate mirror. The flag is
        recorded in the returned audit dict ONLY when true, like
        `unresolvedEntrypoints`. The Oracle emits no
        SOURCE_NOT_ENUMERATED finding of its own for this (its
        convention: INCOMPLETE is forced through the ground-truth
        flag, exactly like the non-OK parse status / UNREADABLE
        unknown); the production comparator is the one that emits
        the section 5.1 finding.
      * Unreadable or malformed TS parse config (FIX P024 R2 P1-01):
        `tsconfig.json` / `package.json` exists but could not be
        read or parsed (gt unknownImports with reason
        CONFIG_UNREADABLE, from = the config path; gt
        tsconfigStatus / packageJsonStatus "UNREADABLE" /
        "MALFORMED") -- the config is UNKNOWN, not absent.
        Resolution is per-config: steps whose config IS known still
        resolve (a readable tsconfig's aliases, a readable
        package.json's self-references, a known baseUrl); only a
        bare specifier no known step resolves, while either config
        is UNKNOWN, is ("unknown", "CONFIG_UNREADABLE"), never
        external -- exactly like production resolveSpecifier. The
        audit emits one SOURCE_NOT_ENUMERATED finding per config
        path and is INCOMPLETE, never PASS. This DELIBERATELY
        differs from the toml convention above: the finding is the
        channel that names the config path, as the R2 fix requires.
        SOURCE_NOT_ENUMERATED is INCOMPLETE-forcing, never
        FAIL-class (it is not in FAIL_FINDING_IDS), mirroring
        production compare.ts Rule 9.
      * MISSING_EDGE / UNCLAIMED_REACHABLE_MODULE: FULL_GRAPH only.
      * NAME_COLLISION_CONFUSION: a hallucinated edge to a REAL module
        and a missing edge share the same source and target basename.
      * DYNAMIC_IMPORT_UNKNOWN: a module with unresolvable dynamic imports.
      * Status: FAIL if any FAIL-class finding; else INCOMPLETE if any
        DYNAMIC_IMPORT_UNKNOWN, SOURCE_NOT_ENUMERATED finding,
        non-dynamic unknown import, non-OK parse status, unresolvable
        declared entrypoint, unreadable entrypoint declaration,
        unreadable/malformed TS parse config, or STALE_SNAPSHOT;
        else PASS. The STALE_SNAPSHOT case short-circuits BEFORE any
        finding is computed (FIX T013 R3, R3-P1-01): a stale map is
        INCOMPLETE with zero findings, so a FAIL-class finding can never
        outrank a stale snapshot. An unresolvable declaration never
        outranks a FAIL-class finding either (production Rule 9: FAIL
        wins), but it does force INCOMPLETE on an otherwise clean map.
      * ISOLATED_MODULE is report info only and is never a finding here.
    """
    # FIX T013 R4 (R4-P1-01): resolve the declared entrypoints against
    # the ground-truth modules BEFORE the stale short-circuit, so the
    # unresolved list is recorded in every return (stale or not) --
    # production's Rule 1 short-circuit and Rule 9 both yield
    # INCOMPLETE, and the unresolved declaration is a fact about the
    # tree+declaration either way.
    if declared_literal_entrypoints is None:
        unresolved_entrypoints = []
    else:
        unresolved_entrypoints = _resolve_declared_entrypoints(
            declared_literal_entrypoints, gt["modules"])[1]
    audit_extra = ({"unresolvedEntrypoints": unresolved_entrypoints}
                   if unresolved_entrypoints else {})
    # FIX P024 R1 P1-01 follow-up: an unreadable .repomapverify.toml
    # leaves the entrypoint declaration UNKNOWN, not absent (see the
    # docstring). Recorded ONLY when true, like unresolvedEntrypoints.
    toml_unreadable = bool(gt.get("entrypointsDeclarationUnreadable"))
    if toml_unreadable:
        audit_extra = {**audit_extra,
                       "entrypointsDeclarationUnreadable": True}
    # FIX T013 R3 (R3-P1-01): resolve the snapshot FIRST and mirror
    # production Rule 1 exactly -- on STALE_SNAPSHOT (including the
    # snapshot-conflict case) return INCOMPLETE with NO findings of any
    # kind, before computing any blame finding. unknownImportsPresent
    # is still computed from ground truth: it is a fact about the
    # current tree, not a blame finding on the claimed map.
    claimed_snapshot, snapshot_conflict = _resolve_claimed_snapshot(claimed)
    snapshot_status = ("MATCH" if not snapshot_conflict
                       and claimed_snapshot == gt["repoSnapshotSha256"]
                       else "STALE_SNAPSHOT")
    unknown_present = bool(
        [u for u in gt["unknownImports"]
         if u["reason"] != "DYNAMIC_IMPORT_UNKNOWN"])
    if snapshot_status == "STALE_SNAPSHOT":
        return {"status": "INCOMPLETE", "snapshotStatus": snapshot_status,
                "findings": [], "unknownImportsPresent": unknown_present,
                **audit_extra}
    real_modules = {m["relativePath"] for m in gt["modules"]}
    real_edges = {(e["from"], e["to"]) for e in gt["edges"]}
    reachable = set(gt["reachableFromEntrypoints"])
    declared = gt["entrypoints"]  # resolved declaration (FIX T013 R4:
    # gt entrypoints are the RESOLVED module paths only, matching
    # production's declaredEntrypoints; go: package dirs)
    completeness = claimed.get("completeness", "FULL_GRAPH")
    claimed_modules = [m["path"] for m in claimed.get("modules", [])]
    claimed_edges = [(e["from"], e["to"]) for e in claimed.get("edges", [])]
    claimed_entries = claimed.get("entrypoints", [])
    findings = []
    # FIX P024 R1 P1-01: paths hidden behind an unreadable file or
    # directory are UNKNOWN, not hallucinated -- mirror of production
    # compare.ts Rules 2/3 (spec section 5.1: ENOENT is hallucination,
    # an unreadable path is not). A claimed path equal to, under, or a
    # parent directory of an unreadable path (gt unknownImports with
    # reason UNREADABLE) may well exist; the auditor simply cannot see
    # it. The audit is INCOMPLETE anyway via the UNREADABLE unknown /
    # non-OK parse status, so no blame finding is lost -- only a false
    # FAIL is avoided.
    hidden = [u["from"] for u in gt["unknownImports"]
              if u["reason"] == "UNREADABLE"]

    def _is_hidden(p):
        for h in hidden:
            if h == "." or p == h or p.startswith(h + "/") \
                    or h.startswith(p + "/"):
                return True
        return False

    for path in claimed_modules:
        if path not in real_modules and not _is_hidden(path):
            findings.append({"id": "HALLUCINATED_MODULE", "from": path})
    # FIX T013 (P2-01): module-level GENERATED_MISMATCH. Only when the
    # map asserts generated true/false; absent means no assertion.
    # P2 severity, never FAIL-class, never INCOMPLETE-forcing -- the
    # module itself is verified to exist, only its generated-ness
    # assertion is wrong (same stance as production compare.ts).
    real_generated = {m["relativePath"]: m["isGenerated"]
                      for m in gt["modules"]}
    for m in claimed.get("modules", []):
        asserted = m.get("generated")
        if (isinstance(asserted, bool) and m["path"] in real_generated
                and real_generated[m["path"]] != asserted):
            findings.append({"id": "GENERATED_MISMATCH", "from": m["path"]})
    for frm, to in claimed_edges:
        if (frm, to) not in real_edges \
                and not (_is_hidden(frm) or _is_hidden(to)):
            findings.append({"id": "HALLUCINATED_EDGE", "from": frm, "to": to})
    if declared:
        # FIX T013 (P1-01): accept both the ground-truth spelling and
        # the literal toml spelling of each declared entrypoint.
        accepted = set(declared)
        if declared_literal_entrypoints:
            accepted.update(declared_literal_entrypoints)
        for entry in claimed_entries:
            if entry not in accepted:
                findings.append({"id": "WRONG_ENTRYPOINT", "from": entry})
    missing = []
    if completeness == "FULL_GRAPH":
        claimed_edge_set = set(claimed_edges)
        for frm, to in sorted(real_edges):
            if (frm, to) not in claimed_edge_set:
                rec = {"id": "MISSING_EDGE", "from": frm, "to": to}
                findings.append(rec)
                missing.append(rec)
        claimed_module_set = set(claimed_modules)
        for path in sorted(reachable):
            if path not in claimed_module_set:
                findings.append({"id": "UNCLAIMED_REACHABLE_MODULE",
                                 "from": path})
    # NAME_COLLISION_CONFUSION: a hallucinated edge whose target is a
    # REAL module, and a missing edge from the same source whose target
    # shares that basename (the agent confused two same-named modules).
    # When the hallucinated target does not exist at all (py-p08's
    # invented top-level utils.py) there is no confusion between two real
    # modules, only a hallucination -- no NAME_COLLISION finding.
    hallucinated = [f for f in findings if f["id"] == "HALLUCINATED_EDGE"]
    for h in hallucinated:
        if h["to"] not in real_modules:
            continue
        h_base = h["to"].split("/")[-1]
        for m in missing:
            if m["from"] == h["from"] and m["to"].split("/")[-1] == h_base:
                findings.append({"id": "NAME_COLLISION_CONFUSION",
                                 "from": h["from"], "to": h["to"]})
                break
    for dyn in gt["dynamicUnknown"]:
        findings.append({"id": "DYNAMIC_IMPORT_UNKNOWN", "from": dyn["path"]})
    for unk in gt["unknownImports"]:
        if unk["reason"] == "DYNAMIC_IMPORT_UNKNOWN":
            findings.append({"id": "DYNAMIC_IMPORT_UNKNOWN",
                             "from": unk["from"]})
    # FIX P024 R2 P1-01: a TS parse config that exists but could not
    # be read or parsed is UNKNOWN, not absent (see
    # TypeScriptOracle). Each such config gets its own
    # SOURCE_NOT_ENUMERATED finding naming the config path --
    # mirroring production compare.ts Rules 6/7 (spec section 5.1:
    # an unreadable path gets a finding naming the path, so the
    # audit is INCOMPLETE with the cause visible instead of PASSing
    # over a hole in the tree). One finding per config path: only
    # the config's own unknownImports entry (from = the config path,
    # specifier empty) carries a finding. The import entries that
    # cite the same reason (from = the importing file) stay
    # unknownImports -- they force INCOMPLETE via unknownPresent,
    # but they are not themselves un-enumerated sources, so they
    # get no finding of their own.
    for unk in gt["unknownImports"]:
        if unk["reason"] == CONFIG_UNREADABLE_REASON \
                and unk["from"] in ("tsconfig.json", "package.json"):
            findings.append({"id": "SOURCE_NOT_ENUMERATED",
                             "from": unk["from"]})
    findings.sort(key=lambda f: (f["id"], f.get("from", ""), f.get("to", "")))
    # snapshot_status / unknown_present were resolved at the top of this
    # function (FIX T013 R3, R3-P1-01); reaching here means MATCH, so
    # the snapshot can no longer force INCOMPLETE.
    if any(f["id"] in FAIL_FINDING_IDS for f in findings):
        status = "FAIL"
    elif (any(f["id"] == "DYNAMIC_IMPORT_UNKNOWN" for f in findings)
          or any(f["id"] == "SOURCE_NOT_ENUMERATED" for f in findings)
          or unknown_present
          or unresolved_entrypoints
          or toml_unreadable
          or any(m["parseStatus"] != "OK" for m in gt["modules"])):
        status = "INCOMPLETE"
    else:
        status = "PASS"
    return {"status": status, "snapshotStatus": snapshot_status,
            "findings": findings, "unknownImportsPresent": unknown_present,
            **audit_extra}


